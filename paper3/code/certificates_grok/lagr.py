#!/usr/bin/env python3
"""R25 core library: the stochastic-Lagrangian monoid Sigma(q_{a,b}) for the mixed Z4 form
q_{a,b}(x) = |x_A| - |x_B| mod 4 on F_2^t (A = first a coords, B = last b coords), t = a+b.
Sigma(q) = { T subset F_2^t (+) F_2^t : dim T = t, (q (+) -q)|_T = 0 mod 4, 1_{2t} in T }   (HL Lemma 6 index set).
Enumeration: q(+)-q is even on 1^perp, Q = (q(+)-q)/2 mod 2 is a nondegenerate F_2 quadratic form on 1^perp/<1> (dim 2t-2);
Sigma(q) <-> Lagrangians (maximal totally singular subspaces) of that space, generated by an explicit duplicate-free recursion.
Elements: (x,y) encoded as int x | y<<t.  r(T) = sum_{(x,y) in T} |x><y| ; r(T1) r(T2) = 2^{d} r(T1 o T2)."""
import itertools, random
def popc(v): return bin(v).count("1")
class Space:
    def __init__(s, a, b):
        s.a, s.b, s.t = a, b, a+b
        s.maskA = (1 << a) - 1; s.maskB = ((1 << s.t) - 1) ^ s.maskA; s.full = (1 << s.t) - 1
    def q(s, x): return (popc(x & s.maskA) - popc(x & s.maskB)) % 4
    def Q4(s, u): t = s.t; return (s.q(u & s.full) - s.q(u >> t)) % 4
    def B(s, u, v): return popc(u & v) & 1
def rref(vecs):
    """canonical reduced row echelon basis (tuple, decreasing pivots) of span(vecs) over F_2"""
    basis = []
    for v in vecs:
        for b in basis:
            if v ^ b < v: v ^= b  # reduce by leading bit
        if v:
            basis = [b ^ v if (b ^ v) < b else b for b in basis]  # clear v's leading bit in others
            basis.append(v); basis.sort(reverse=True)
    # full reduction pass
    out = sorted(basis, reverse=True)
    for i in range(len(out)):
        for j in range(len(out)):
            if i != j and (out[j] >> (out[i].bit_length()-1)) & 1: out[j] ^= out[i]
    return tuple(sorted(out, reverse=True))
def span_elems(basis):
    el = [0]
    for b in basis: el += [e ^ b for e in el]
    return el
def hyperbolic_basis(S):
    """symplectic/hyperbolic basis (e_i,f_i) of 1^perp/<1> for Q = Q4/2, using an explicit complement of <1> in 1^perp"""
    n2 = 2*S.t
    W = [1 | (1 << j) for j in range(1, n2-1)]  # e0+ej, j=1..2t-2: complement of <1> inside 1^perp
    Qf = lambda u: (S.Q4(u) // 2) % 2
    pairs = []
    while W:
        el = span_elems(W)
        e = next((u for u in el if u and Qf(u) == 0), None)
        assert e is not None, "no singular vector: Witt index smaller than expected"
        f = next(u for u in el if S.B(e, u))
        if Qf(f): f ^= e
        assert Qf(f) == 0 and S.B(e, f) == 1
        pairs.append((e, f))
        newW = []
        for v in W:
            v2 = v ^ (e if S.B(v, f) else 0) ^ (f if S.B(v, e) else 0)
            newW.append(v2)
        W = [v for v in rref(newW)]
        W = [v for v in W if v]
        # remove e,f directions: newW lies in <e,f>^perp; its span has dim len(W)-2
        Wr = rref(newW)
        assert len(Wr) == len(newW) - 2 or len(Wr) == len(newW)-1 or True
        W = list(rref([v for v in newW]))
        # keep exactly a basis of <e,f>^perp within previous W
        W = [v for v in W if v]
        if len(W) > 0 and len(W) == len(newW):  # should not happen
            raise RuntimeError
    return pairs
def lagrangians_hyp(m):
    """all Lagrangians of the standard hyperbolic F_2 quadratic space Q(a,b)=sum a_i b_i on F_2^{2m};
    vector = (abits, bbits) as int abits | bbits<<m. Returns list of bases (lists of ints). Count prod_{i=0}^{m-1}(2^i+1)."""
    if m == 0: return [[]]
    out = []
    sub = lagrangians_hyp(m-1)   # on indices 1..m-1 (shifted by 1 inside abits/bbits)
    def lift(v):  # (m-1)-space vector -> m-space vector on indices 1..m-1
        a, b = v & ((1 << (m-1)) - 1), v >> (m-1)
        return (a << 1) | (b << 1) << m
    e0, f0 = 1, 1 << m
    Bf = lambda u, v: (popc((u & ((1 << m)-1)) & (v >> m)) + popc((v & ((1 << m)-1)) & (u >> m))) & 1
    Qf = lambda u: popc((u & ((1 << m)-1)) & (u >> m)) & 1
    for Lp in sub:
        L = [lift(v) for v in Lp]
        out.append([e0] + L)
        # dual vectors u_j in W with B(u_i, l_j) = delta_ij : solve over the W-basis
        Wbasis = [lift(1 << i) for i in range(m-1)] + [lift(1 << (m-1+i)) for i in range(m-1)]
        duals = []
        for j in range(m-1):
            # find combination of Wbasis with B(.,L[i]) = delta_ij  (brute force over solution via linear algebra)
            rows = [(sum(Bf(w, L[i]) << idx for idx, w in enumerate(Wbasis)), 1 if i == j else 0) for i in range(m-1)]
            # Gaussian elimination
            piv = []; rr = []
            for r, c in rows:
                for (pr, pc, pb) in piv:
                    if (r >> pb) & 1: r ^= pr; c ^= pc
                if r:
                    pb = r.bit_length()-1; piv = [(pr ^ r, pc ^ c, pbb) if (pr >> pb) & 1 else (pr, pc, pbb) for (pr, pc, pbb) in piv]
                    piv.append((r, c, pb))
                else: assert c == 0
            sol = 0
            for (pr, pc, pb) in piv:
                if pc: sol |= 1 << pb
            u = 0
            for idx, w in enumerate(Wbasis):
                if (sol >> idx) & 1: u ^= w
            assert all(Bf(u, L[i]) == (1 if i == j else 0) for i in range(m-1))
            duals.append(u)
        for phi in range(1 << (m-1)):
            basis = [L[j] ^ (e0 if (phi >> j) & 1 else 0) for j in range(m-1)]
            w = 0
            for j in range(m-1):
                if (phi >> j) & 1: w ^= duals[j]
            v = f0 ^ w ^ (e0 if Qf(w) else 0)
            basis.append(v)
            out.append(basis)
    return out
def sigma(S):
    """enumerate Sigma(q_{a,b}) as canonical rref tuples (ints in 2t bits)"""
    pairs = hyperbolic_basis(S); m = len(pairs); assert m == S.t - 1, m
    def emb(v):
        u = 0
        for i, (e, f) in enumerate(pairs):
            if (v >> i) & 1: u ^= e
            if (v >> (m+i)) & 1: u ^= f
        return u
    ONE = (1 << (2*S.t)) - 1
    res = []
    for Lb in lagrangians_hyp(m):
        T = rref([emb(v) for v in Lb] + [ONE])
        assert len(T) == S.t
        res.append(T)
    return res
def check_T(S, T):
    ONE = (1 << (2*S.t)) - 1
    if len(T) != S.t: return False
    if any(S.Q4(v) for v in T): return False
    if any(S.B(u, v) for u in T for v in T): return False
    return rref(list(T) + [ONE]) == T
def compose(S, T1, T2):
    """T1 o T2 = {(x,z): exists y, (x,y) in T1, (y,z) in T2};  d = dim{y: (0,y) in T1, (y,0) in T2}.  Returns (rref, d)."""
    t = S.t; F = S.full
    # vectors in 3t bits: x | y<<t | z<<2t, with the constraint carried as 'syndrome' y1^y2
    vecs = []
    for u in T1: vecs.append(((u & F) | ((u >> t) << t), u >> t))         # (x, y, 0) syndrome y
    for u in T2: vecs.append((((u >> t) << 2*t), u & F))  # (0, 0, z) syndrome y   (y is recorded once, from T1)
    # kernel of syndrome map
    piv = []  # (syndrome, vec)
    ker = []
    for v, s in vecs:
        for ps, pv in piv:
            if s ^ ps < s: s ^= ps; v ^= pv
        if s: piv.append((s, v)); piv.sort(key=lambda p: -p[0])
        else: ker.append(v)
    # ker: vectors (x,y,z) with consistent y (y appears once: x|y<<t from T1 and y<<t from T2 XOR -> y fields add; consistency enforced by syndrome)
    proj = [(v & F) | ((v >> 2*t) << t) for v in ker]
    R = rref(proj)
    d = len(ker) - len(R)   # (T1 (+) T2) -> (vector, syndrome) is injective, so len(ker) = dim of the fibre product
    return R, d
def graph(S, g):
    """T_g = {(g x, x)} for a linear map g given as list of images of basis vectors"""
    t = S.t
    def ap(x):
        y = 0
        for i in range(t):
            if (x >> i) & 1: y ^= g[i]
        return y
    return rref([ap(1 << i) | ((1 << i) << t) for i in range(t)])
def left_defect(S, T):
    return [u & S.full for u in span_elems(T) if (u >> S.t) == 0]
